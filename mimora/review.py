"""Ebbinghaus spaced-repetition review store for practiced phrases.

Every phrase the user practices - from the practice text, or generated by the
LLM - is tracked here with a per-phrase review state driven by the Ebbinghaus
forgetting curve: a phrase you recalled well is reviewed again after a longer
interval (1, 2, 4, 7, 15, 30, 60 days), and one you failed comes back the next
day. The phrase-source selection (mimora/phrase_source.py, app.py) consults
this store so due phrases reappear on the Ebbinghaus schedule instead of only
cycling fresh text.

Pure Python, no Tk, no engine imports - it must stay importable by the phrase
provider and by unit tests without dragging in the GUI. Persistence mirrors
:class:`mimora.persistence.stats.StatsStore`: one JSON file next to
settings.json, atomic replace plus a rolling ``.bak`` snapshot.
"""

import json
import logging
import os
import threading
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any, Dict, List, Optional

# Ebbinghaus forgetting-curve review intervals, in days. The index into this
# tuple is the phrase's current review step: the next review happens
# ``intervals[index]`` days after the last one. A pass advances the index
# (bounded), a fail resets it to 0 (the soonest step) - the classic curve,
# where each successful recall lengthens the spacing and a forgotten item
# comes back quickly.
EBBINGHAUS_INTERVALS_DAYS = (1, 2, 4, 7, 15, 30, 60)

REVIEW_SCHEMA_VERSION = 1

# Sources a phrase can be recorded under. "practice" = a sentence from the
# practice text, "llm" = a phrase the LLM generated (recorded separately so
# the bank can be reviewed on its own).
SOURCE_CHOICES = ("practice", "llm")


def _iso(dt: datetime) -> str:
    return dt.isoformat(timespec="seconds")


def _now_dt() -> datetime:
    return datetime.now()


def _parse_iso(value: Optional[str]) -> Optional[datetime]:
    if not value:
        return None
    try:
        return datetime.fromisoformat(value)
    except ValueError:
        return None


class ReviewStore:
    """Load/save the review state and advance phrases on the Ebbinghaus curve.

    Owns the in-memory ``data`` dict. Mutating methods persist immediately
    (atomic replace + ``.bak``); reads are pure.

    ``path`` defaults to ``config.review_path()`` and can be overridden by a
    test that points it at a temporary file.
    """

    def __init__(self, path: Optional[str] = None):
        if path is None:
            from mimora import config
            path = config.review_path()
        self._path = Path(path)
        self._lock = threading.RLock()
        self.data: Dict[str, Any] = self._empty_data()

    # -- lifecycle -----------------------------------------------------------

    def _empty_data(self) -> Dict[str, Any]:
        return {
            "version": REVIEW_SCHEMA_VERSION,
            "created_at": _iso(_now_dt()),
            "phrases": {},
        }

    def load(self) -> None:
        """Load ``review.json`` into ``self.data`` (best-effort)."""
        with self._lock:
            if not self._path.exists():
                self.data = self._empty_data()
                return
            try:
                with open(self._path, "r", encoding="utf-8") as fh:
                    raw = json.load(fh)
                if not isinstance(raw, dict) or "phrases" not in raw:
                    raise ValueError("review.json is not a review file")
                self.data = raw
            except Exception as exc:
                logging.warning("Could not read %s (%s); starting fresh",
                                self._path, exc)
                self.data = self._empty_data()

    def _write_atomic(self, target: Path) -> None:
        tmp = target.with_suffix(target.suffix + ".tmp")
        with open(tmp, "w", encoding="utf-8") as fh:
            json.dump(self.data, fh, ensure_ascii=False, indent=2)
        os.replace(tmp, target)

    def save(self) -> None:
        """Persist atomically, keeping a one-step ``.bak`` snapshot."""
        with self._lock:
            try:
                if self._path.exists():
                    bak = self._path.with_suffix(self._path.suffix + ".bak")
                    try:
                        os.replace(self._path, bak)
                    except OSError:
                        pass
                self._write_atomic(self._path)
            except OSError as exc:
                logging.warning("Could not write %s (%s)", self._path, exc)

    # -- helpers -------------------------------------------------------------

    @staticmethod
    def _state(phrase: str) -> Dict[str, Any]:
        """A fresh review-state dict for *phrase* (not yet saved)."""
        return {
            "phrase": phrase,
            "source": "practice",
            "first_seen": None,
            "last_reviewed": None,
            "next_review_at": None,   # None = never reviewed (not yet due)
            "interval_index": 0,
            "seen": 0,
            "passed": False,
        }

    def _get(self, phrase: str) -> Optional[Dict[str, Any]]:
        return self.data.get("phrases", {}).get(phrase)

    # -- public API ----------------------------------------------------------

    def record_phrase(self, phrase: str, source: str = "practice",
                      now: Optional[datetime] = None) -> Dict[str, Any]:
        """Ensure *phrase* is tracked (add it if new) and return its state.

        Recording a phrase for the first time does NOT schedule a review: a
        fresh phrase is the one being practiced now, and its next review is
        set only once it has actually been scored (see record_result). The
        ``source`` is recorded so LLM phrases form a separate review bank.

        Idempotent: an already-known phrase keeps its existing state and only
        has ``source`` corrected if it was never seen.
        """
        now = now or _now_dt()
        with self._lock:
            state = self._get(phrase)
            if state is None:
                state = self._state(phrase)
                state["source"] = source if source in SOURCE_CHOICES else "practice"
                state["first_seen"] = _iso(now)
                self.data.setdefault("phrases", {})[phrase] = state
                self.save()
            return state

    def record_result(self, phrase: str, passed: bool,
                      now: Optional[datetime] = None) -> Dict[str, Any]:
        """Record a scored take and advance the phrase's Ebbinghaus schedule.

        On the first result the phrase gets its first review interval (1 day
        later) whether it passed or not. On a later result a pass advances the
        interval index (2, 4, 7, ... days) and a fail resets it to the soonest
        step. Returns the updated state.
        """
        now = now or _now_dt()
        with self._lock:
            state = self._get(phrase)
            if state is None:
                state = self.record_phrase(phrase, now=now)
            index = int(state.get("interval_index", 0))
            reviewed_before = state.get("last_reviewed") is not None
            if not passed:
                index = 0
            elif reviewed_before:
                index = min(index + 1, len(EBBINGHAUS_INTERVALS_DAYS) - 1)
            # First result: index stays 0 → next review in 1 day (pass or fail).
            state["interval_index"] = index
            state["last_reviewed"] = _iso(now)
            state["next_review_at"] = _iso(
                now + timedelta(days=EBBINGHAUS_INTERVALS_DAYS[index]))
            state["seen"] = int(state.get("seen", 0)) + 1
            state["passed"] = bool(passed)
            self.save()
            return state

    def is_due(self, phrase: str, now: Optional[datetime] = None) -> bool:
        """True when *phrase* has been reviewed and its next review is due."""
        state = self._get(phrase)
        if state is None:
            return False
        due = _parse_iso(state.get("next_review_at"))
        if due is None:
            return False  # never reviewed (fresh phrase): not a review yet
        return due <= (now or _now_dt())

    def due_phrases(self, now: Optional[datetime] = None,
                    source: Optional[str] = None) -> List[str]:
        """Phrase strings that are due for review, most overdue first.

        ``source`` filters to one bank ("practice" or "llm"). An empty list
        means nothing is due.
        """
        now = now or _now_dt()
        result = []
        for phrase, state in self.data.get("phrases", {}).items():
            if source is not None and state.get("source") != source:
                continue
            due = _parse_iso(state.get("next_review_at"))
            if due is not None and due <= now:
                result.append((due, phrase))
        result.sort()  # earliest due first = most overdue
        return [phrase for _, phrase in result]

    def phrase_state(self, phrase: str) -> Optional[Dict[str, Any]]:
        """The stored state for *phrase*, or None if it is not tracked."""
        state = self._get(phrase)
        return dict(state) if state else None

    def all_phrases(self, source: Optional[str] = None
                    ) -> List[Dict[str, Any]]:
        """All tracked phrase states, optionally filtered by source."""
        result = []
        for state in self.data.get("phrases", {}).values():
            if source is not None and state.get("source") != source:
                continue
            result.append(dict(state))
        return result
